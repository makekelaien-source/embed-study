/* d3-ex3.c - 练习3: 两个数的正负组合（&& 和 ||）
 * 用到讲义: 第5节 && 与 || 组合, 第4节 else if 顺序
 * 规则: 两个都 > 0 -> 都是正数
 *       至少一个 > 0 -> 至少一个正数
 *       一个都没有   -> 都不是正数
 * 测试输入: 3 5 -> 都是正数   -2 4 -> 至少一个正数   0 -1 -> 都不是正数
 */
#include <stdio.h>

int main(void)
{
    int a = 0;
    int b = 0;

    printf("请输入两个整数: ");
    scanf("%d %d", &a, &b);

    if (a > 0 && b > 0/* TODO: 两个都大于 0, 用 && */) {
        printf("都是正数\n");
    } else if (a > 0 || b > 0/* TODO: 至少一个大于 0, 用 || */) {
        printf("至少一个正数\n");
    } else {
        printf("都不是正数\n");
    }

    return 0;
}
